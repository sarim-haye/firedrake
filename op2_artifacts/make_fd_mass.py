"""Generate the ``fd_mass`` OP2 artifact from a real Firedrake form.

Form: ``c * v * dx`` with P2 test function ``v`` on ``UnitSquareMesh(3, 3)``.
The local kernel has arguments ``A[6]`` (INC, one entry per P2 node of the
cell), ``coords[6]`` (READ, three vertices x (x, y)) and ``c[1]`` (READ).

OP2 sees those as 6 + 3 + 1 op_args, in this order::

    A0..A5  op_arg_dat(result, i, cell2node, 1, OP_INC)
    X0..X2  op_arg_dat(coords, i, cell2vert, 2, OP_READ)
    c       op_arg_gbl(&c, 1, OP_READ)

Besides the artifact this writes ``fd_mass_data.h``: the mesh, both maps in
Firedrake's local ordering, and Firedrake's own assembled vector as the
reference answer for the OP2 test.

Run with the MLIR branch environment::

    PYTHONPATH=firedrake-mlir:fiat-mlir python firedrake-mlir/op2_artifacts/make_fd_mass.py
"""

from pathlib import Path

import numpy as np
from firedrake import Constant, FunctionSpace, TestFunction, UnitSquareMesh, assemble, dx

from fd2op2 import Op2Arg, capture_local_kernels, write_artifact

HERE = Path(__file__).resolve().parent
NAME = "fd_mass"
C_VALUE = 10.0


def main():
    mesh = UnitSquareMesh(3, 3)
    V = FunctionSpace(mesh, "P", 2)
    v = TestFunction(V)

    with capture_local_kernels() as kernels:
        result = assemble(
            Constant(C_VALUE) * v * dx,
            pyop3_compiler_parameters={"backend": "gem"},
            form_compiler_parameters={"backend": "gem"},
        )
    assert len(kernels) == 1, f"expected one local kernel, got {len(kernels)}"
    kernel = kernels[0]
    print("local kernel args:", list(zip(kernel.arg_names, kernel.shapes, kernel.intents)))

    A, X, C = kernel.arg_names
    op2_args = (
        [Op2Arg(A, i, 1) for i in range(6)]
        + [Op2Arg(X, 2 * i, 2) for i in range(3)]
        + [Op2Arg(C, 0, 1)]
    )
    mlir_path = write_artifact(kernel, op2_args, NAME, HERE / f"{NAME}.h", HERE)
    print("wrote", mlir_path)

    write_test_data(mesh, V, result.dat.data_ro)


def c_array(ctype, name, values):
    flat = ", ".join(repr(float(x)) if ctype == "double" else str(int(x))
                     for x in np.asarray(values).ravel())
    return f"static const {ctype} {name}[] = {{{flat}}};\n"


def write_test_data(mesh, V, reference):
    coords = mesh.coordinates.dat.data_ro
    cell2vert = mesh.coordinates.function_space().cell_node_list
    cell2node = V.cell_node_list
    lines = [
        "// Generated by make_fd_mass.py - Firedrake mesh, maps and reference result.\n",
        "#pragma once\n",
        f"static const int fd_mass_ncells = {cell2node.shape[0]};\n",
        f"static const int fd_mass_nverts = {coords.shape[0]};\n",
        f"static const int fd_mass_nnodes = {reference.shape[0]};\n",
        f"static const double fd_mass_c = {C_VALUE!r};\n",
        c_array("double", "fd_mass_coords", coords),
        c_array("int", "fd_mass_cell2vert", cell2vert),
        c_array("int", "fd_mass_cell2node", cell2node),
        c_array("double", "fd_mass_reference", reference),
    ]
    (HERE / f"{NAME}_data.h").write_text("".join(lines))
    print(f"wrote {NAME}_data.h: {cell2node.shape[0]} cells, {coords.shape[0]} vertices, "
          f"{reference.shape[0]} P2 nodes, reference sum = {reference.sum():.15g}")


if __name__ == "__main__":
    main()
